#!/usr/bin/env python3
"""
Generates the strongly-typed style API of Mapbox.Net from the official style specifications.

  * Mapbox GL style spec   (@mapbox/mapbox-gl-style-spec  reference/v8.json)
  * MapLibre GL style spec (@maplibre/maplibre-gl-style-spec dist/latest.json)

Both specs are merged: every layer type and property supported by at least one engine is generated,
and the XML documentation states which engine(s) support it.

Usage:
    python tools/generate_style_spec.py [--mapbox-version 14.34.2] [--maplibre-version 26.5.1]
                                        [--mapbox-spec file.json] [--maplibre-spec file.json]

Output: src/Mapbox.Net.Core/Style/Generated/*.g.cs
"""
import argparse
import json
import os
import re
import sys
import urllib.request
from html import escape

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT_DIR = os.path.join(ROOT, "src", "Mapbox.Net.Core", "Style", "Generated")
EXPR_HANDWRITTEN = os.path.join(ROOT, "src", "Mapbox.Net.Core", "Style", "Expression.cs")

HEADER = """// <auto-generated>
//   Generated by tools/generate_style_spec.py from
//   @mapbox/mapbox-gl-style-spec {mb} and @maplibre/maplibre-gl-style-spec {ml}.
//   Do not edit by hand: re-run the generator instead.
// </auto-generated>
#nullable enable
"""

# Layer prefixes used to derive shared enum names (e.g. fill-translate-anchor -> TranslateAnchor).
LAYER_PREFIXES = sorted([
    "fill-extrusion-", "raster-particle-", "color-relief-", "fill-", "line-", "circle-", "heatmap-",
    "icon-", "text-", "symbol-", "raster-", "hillshade-", "sky-", "model-", "background-", "clip-", "building-",
], key=len, reverse=True)

OPERATOR_NAMES = {
    "!": "Not", "!=": "NotEqual", "%": "Mod", "*": "Multiply", "+": "Add", "-": "Subtract", "/": "Divide",
    "<": "LessThan", "<=": "LessOrEqual", "==": "Equal", ">": "GreaterThan", ">=": "GreaterOrEqual", "^": "Pow",
    "to-string": "ToStringOf", "typeof": "TypeOf",
}

CSHARP_KEYWORDS = {"object", "string", "bool", "double", "int", "in", "case", "var", "let", "base", "params", "event",
                   "operator", "is", "as", "new", "this", "default", "true", "false", "null", "typeof", "array"}


def load(path_or_url):
    if os.path.exists(path_or_url):
        with open(path_or_url, encoding="utf-8") as f:
            return json.load(f)
    with urllib.request.urlopen(path_or_url) as r:  # nosec - official npm CDN
        return json.loads(r.read().decode("utf-8"))


def pascal(name):
    parts = re.split(r"[-_\s.]+", name)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def kebab_of_pascal(name):
    out = []
    for i, c in enumerate(name):
        if c.isupper():
            prev_lower = i > 0 and (name[i - 1].islower() or name[i - 1].isdigit())
            prev_upper = i > 0 and name[i - 1].isupper()
            next_lower = i + 1 < len(name) and name[i + 1].islower()
            if i > 0 and (prev_lower or (prev_upper and next_lower)):
                out.append("-")
            out.append(c.lower())
        else:
            out.append(c)
    return "".join(out)


def xml_doc(text):
    if not text:
        return ""
    text = escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<c>\1</c>", text)
    return text.replace("\r", "")


def doc_lines(summary, remarks=None, indent="    "):
    lines = [f"{indent}/// <summary>"]
    for line in (summary or "").split("\n"):
        lines.append(f"{indent}/// {line}".rstrip())
    lines.append(f"{indent}/// </summary>")
    if remarks:
        lines.append(f"{indent}/// <remarks>")
        for r in remarks:
            lines.append(f"{indent}/// {r}".rstrip())
        lines.append(f"{indent}/// </remarks>")
    return lines


class Prop:
    def __init__(self, name, kind):
        self.name = name
        self.kind = kind  # 'paint' | 'layout' | 'root'
        self.mb = None
        self.ml = None

    @property
    def spec(self):
        return self.mb or self.ml

    def enum_values(self):
        vals = {}
        for s in (self.mb, self.ml):
            if s and isinstance(s.get("values"), dict):
                for v, meta in s["values"].items():
                    vals.setdefault(v, (meta or {}).get("doc", "") if isinstance(meta, dict) else "")
        return vals


def merge_group(mb_group, ml_group, kind):
    props = {}
    for src, attr in ((mb_group or {}, "mb"), (ml_group or {}, "ml")):
        for name, spec in src.items():
            if not isinstance(spec, dict) or spec.get("private"):
                continue
            p = props.setdefault(name, Prop(name, kind))
            setattr(p, attr, spec)
    return props


class EnumRegistry:
    def __init__(self):
        self.enums = {}  # name -> (values dict, prop names)

    def plan(self, all_props):
        """Decides enum names: shared short names for identical value sets, full names otherwise."""
        by_short = {}
        for p in all_props:
            spec = p.spec
            if not (spec["type"] == "enum" or (spec["type"] == "array" and spec.get("value") == "enum")):
                continue
            short = p.name
            for pref in LAYER_PREFIXES:
                if short.startswith(pref):
                    short = short[len(pref):]
                    break
            by_short.setdefault(short, []).append(p)

        self.prop_enum = {}
        for short, plist in by_short.items():
            value_sets = {tuple(sorted(p.enum_values().keys())) for p in plist}
            if len(plist) > 1 and len(value_sets) == 1:
                name = pascal(short)
                self._register(name, plist[0].enum_values(), plist)
            else:
                for p in plist:
                    self._register(pascal(p.name), p.enum_values(), [p])

    def _register(self, name, values, plist):
        if name in ("Type", "Visibility") and plist[0].name != "visibility":
            name = pascal(plist[0].name)
        existing = self.enums.get(name)
        if existing:
            merged = dict(existing[0]); merged.update(values)
            self.enums[name] = (merged, existing[1] + plist)
        else:
            self.enums[name] = (dict(values), list(plist))
        for p in plist:
            self.prop_enum[id(p)] = name

    def name_for(self, p):
        return self.prop_enum[id(p)]

    def emit(self):
        lines = []
        for name in sorted(self.enums):
            values, plist = self.enums[name]
            used_by = ", ".join(sorted({f"<c>{p.name}</c>" for p in plist}))
            lines += doc_lines(f"Values of the {used_by} style property.", indent="")
            lines.append(f"public enum {name}")
            lines.append("{")
            for v, d in values.items():
                member = pascal(v)
                if member[:1].isdigit():
                    member = "_" + member
                lines += doc_lines(xml_doc(d) or f"<c>{v}</c>")
                if kebab_of_pascal(member) != v:
                    lines.append(f"    [JsonValue(\"{v}\")]")
                lines.append(f"    {member},")
            lines.append("}")
            lines.append("")
        return lines


def cs_type(p, enums):
    spec = p.spec
    t = spec["type"]
    if t == "number":
        return "NumberValue"
    if t == "color":
        return "ColorValue"
    if t == "string":
        return "StringValue"
    if t == "boolean":
        return "BoolValue"
    if t == "formatted":
        return "FormattedValue"
    if t == "resolvedImage":
        return "ImageValue"
    if t == "enum":
        return f"EnumValue<{enums.name_for(p)}>"
    if t in ("padding", "numberArray"):
        return "NumberArrayValue"
    if t == "array":
        v = spec.get("value")
        if v == "number":
            return "NumberArrayValue"
        if v == "string":
            return "StringArrayValue"
        if v == "enum":
            return f"EnumArrayValue<{enums.name_for(p)}>"
    return "AnyValue"


def support_remarks(p):
    r = []
    if p.mb and p.ml:
        r.append("Supported by Mapbox GL JS and MapLibre GL JS.")
    elif p.mb:
        r.append("<b>Mapbox GL JS only.</b>")
    else:
        r.append("<b>MapLibre GL JS only.</b>")
    spec = p.spec
    js = (((spec.get("sdk-support") or {}).get("basic functionality") or {}).get("js")) if p.mb else None
    if js and js not in ("0.10.0",):
        r.append(f"Requires Mapbox GL JS {xml_doc(str(js))}+.")
    facts = []
    if "default" in spec:
        facts.append(f"Default: <c>{xml_doc(json.dumps(spec['default']))}</c>.")
    if "minimum" in spec or "maximum" in spec:
        facts.append(f"Range: {spec.get('minimum', '…')} to {spec.get('maximum', '…')}.")
    if "units" in spec:
        facts.append(f"Units: {xml_doc(spec['units'])}.")
    if spec.get("experimental"):
        facts.append("Experimental.")
    expr = spec.get("expression") or {}
    params = expr.get("parameters") or []
    if "feature" in params:
        facts.append("Supports data-driven styling.")
    elif "zoom" in params:
        facts.append("Supports zoom expressions.")
    if facts:
        r.append(" ".join(facts))
    return r


def emit_property(p, enums, bag):
    typ = cs_type(p, enums)
    prop = pascal(p.name)
    lines = doc_lines(xml_doc(p.spec.get("doc", "") or p.name), support_remarks(p))
    lines.append(f"    public {typ}? {prop}")
    lines.append("    {")
    lines.append(f"        get => {bag}.TryGetValue(\"{p.name}\", out var v) ? v as {typ} : null;")
    lines.append(f"        set => StyleValueHelper.SetOrRemove({bag}, \"{p.name}\", value);")
    lines.append("    }")
    lines.append("")
    if p.kind == "paint" and p.spec.get("transition"):
        lines += doc_lines(f"Transition applied when <see cref=\"{prop}\"/> changes.")
        lines.append(f"    public StyleTransition? {prop}Transition")
        lines.append("    {")
        lines.append(f"        get => {bag}.TryGetValue(\"{p.name}-transition\", out var v) ? v as StyleTransition : null;")
        lines.append(f"        set => StyleValueHelper.SetOrRemove({bag}, \"{p.name}-transition\", value);")
        lines.append("    }")
        lines.append("")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mapbox-version", default="14.34.2")
    ap.add_argument("--maplibre-version", default="26.5.1")
    ap.add_argument("--mapbox-spec")
    ap.add_argument("--maplibre-spec")
    args = ap.parse_args()

    mb = load(args.mapbox_spec or f"https://unpkg.com/@mapbox/mapbox-gl-style-spec@{args.mapbox_version}/reference/v8.json")
    ml = load(args.maplibre_spec or f"https://unpkg.com/@maplibre/maplibre-gl-style-spec@{args.maplibre_version}/dist/latest.json")
    header = HEADER.format(mb=args.mapbox_version, ml=args.maplibre_version)
    os.makedirs(OUT_DIR, exist_ok=True)

    # ---------- layer types ----------
    mb_types = {t: v for t, v in mb["layer"]["type"]["values"].items() if not v.get("private")}
    ml_types = ml["layer"]["type"]["values"]
    layer_types = list(mb_types.keys()) + [t for t in ml_types if t not in mb_types]

    layers = {}
    for t in layer_types:
        paint = merge_group(mb.get(f"paint_{t}"), ml.get(f"paint_{t}"), "paint")
        layout = merge_group(mb.get(f"layout_{t}"), ml.get(f"layout_{t}"), "layout")
        layout.pop("visibility", None)  # handled by the Layer base class
        doc = (mb_types.get(t) or ml_types.get(t) or {}).get("doc", "")
        layers[t] = (paint, layout, doc, t in mb_types, t in ml_types)

    # ---------- root objects ----------
    roots = {
        "Fog": ("fog", merge_group(mb.get("fog"), None, "root"), "Fog / atmosphere settings (<c>map.setFog</c>)."),
        "Terrain": ("terrain", merge_group(mb.get("terrain"), ml.get("terrain"), "root"), "3D terrain settings (<c>map.setTerrain</c>)."),
        "Light": ("light", merge_group(mb.get("light"), ml.get("light"), "root"), "Classic global light (<c>map.setLight</c>)."),
        "Sky": ("sky", merge_group(None, ml.get("sky"), "root"), "Sky / atmosphere settings (<c>map.setSky</c>, MapLibre)."),
        "Snow": ("snow", merge_group(mb.get("snow"), None, "root"), "Snow precipitation effect (<c>map.setSnow</c>, Mapbox)."),
        "Rain": ("rain", merge_group(mb.get("rain"), None, "root"), "Rain precipitation effect (<c>map.setRain</c>, Mapbox)."),
        "AmbientLight": ("ambient", merge_group(mb.get("properties_light_ambient"), None, "root"), "Properties of an <c>ambient</c> 3D light (<c>map.setLights</c>, Mapbox)."),
        "DirectionalLight": ("directional", merge_group(mb.get("properties_light_directional"), None, "root"), "Properties of a <c>directional</c> 3D light (<c>map.setLights</c>, Mapbox)."),
        "FlatLight": ("flat", merge_group(mb.get("properties_light_flat"), None, "root"), "Properties of a <c>flat</c> 3D light (<c>map.setLights</c>, Mapbox)."),
    }
    for r in roots.values():
        for p in r[1].values():
            p.kind = "paint" if p.spec.get("transition") else "root"

    # ---------- enums ----------
    enums = EnumRegistry()
    all_props = [p for (paint, layout, *_rest) in layers.values() for p in list(paint.values()) + list(layout.values())]
    root_props = []
    for cls, (_k, props, _d) in roots.items():
        for p in props.values():
            if p.spec["type"] == "enum":
                p._enum_scope = cls
                root_props.append(p)
    enums.plan(all_props)
    for p in root_props:
        enums._register(f"{pascal(p._enum_scope)}{pascal(p.name)}", p.enum_values(), [p])
    vis_mb = mb["layout_fill"]["visibility"]
    vp = Prop("visibility", "layout"); vp.mb = vis_mb
    enums._register("Visibility", vp.enum_values(), [vp])

    with open(os.path.join(OUT_DIR, "Enums.g.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "using Mapbox.Net.Json;\n\nnamespace Mapbox.Net.Style;\n\n")
        f.write("\n".join(enums.emit()))

    # ---------- layer classes ----------
    out = [header, "using System.Collections.Generic;\n\nnamespace Mapbox.Net.Style;\n"]
    factory = []
    for t, (paint, layout, doc, in_mb, in_ml) in layers.items():
        cls = pascal(t) + "Layer"
        has_source = t not in ("background", "sky", "slot", "clip")
        support = "Supported by Mapbox GL JS and MapLibre GL JS." if in_mb and in_ml else (
            "<b>Mapbox GL JS only.</b>" if in_mb else "<b>MapLibre GL JS only.</b>")
        if t == "clip":
            has_source = True
        out += doc_lines(f"<c>{t}</c> layer: {xml_doc(doc)}", [support], indent="")
        out.append(f"public sealed partial class {cls} : Layer")
        out.append("{")
        out += doc_lines(f"The style-specification type name: <c>{t}</c>.")
        out.append(f"    public const string TypeName = \"{t}\";")
        out.append("")
        if has_source:
            out += doc_lines(f"Creates a <c>{t}</c> layer.")
            out.append("    /// <param name=\"id\">Unique layer id.</param>")
            out.append("    /// <param name=\"source\">Id of the source providing the data.</param>")
            out.append("    /// <param name=\"sourceLayer\">Layer of the vector tile source to use (vector sources only).</param>")
            out.append(f"    public {cls}(string id, string? source = null, string? sourceLayer = null) : base(id, TypeName)")
            out.append("    {")
            out.append("        Source = source;")
            out.append("        SourceLayer = sourceLayer;")
            out.append("    }")
        else:
            out += doc_lines(f"Creates a <c>{t}</c> layer.")
            out.append("    /// <param name=\"id\">Unique layer id.</param>")
            out.append(f"    public {cls}(string id) : base(id, TypeName) {{ }}")
        out.append("")
        for p in layout.values():
            out += emit_property(p, enums, "LayoutProperties")
        for p in paint.values():
            out += emit_property(p, enums, "PaintProperties")
        out.append("}")
        out.append("")
        factory.append(f"        \"{t}\" => new {cls}(id),")

    out.append("public abstract partial class Layer")
    out.append("{")
    out += doc_lines("Creates an empty layer instance of the given style type (unknown types give a <see cref=\"RawLayer\"/>).")
    out.append("    public static Layer CreateOfType(string type, string id) => type switch")
    out.append("    {")
    out += factory
    out.append("        _ => new RawLayer(id, type),")
    out.append("    };")
    out.append("}")
    with open(os.path.join(OUT_DIR, "Layers.g.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    # ---------- root option classes ----------
    out = [header, "namespace Mapbox.Net.Style;\n"]
    for cls, (key, props, doc) in roots.items():
        out += doc_lines(doc, indent="")
        out.append(f"public sealed partial class {cls}Options : StyleObject")
        out.append("{")
        for p in props.values():
            typ = cs_type(p, enums) if p.spec["type"] != "enum" else f"EnumValue<{enums.name_for(p)}>"
            name = pascal(p.name)
            out += doc_lines(xml_doc(p.spec.get("doc", "") or p.name), support_remarks(p))
            out.append(f"    public {typ}? {name}")
            out.append("    {")
            out.append(f"        get => Properties.TryGetValue(\"{p.name}\", out var v) ? v as {typ} : null;")
            out.append(f"        set => StyleValueHelper.SetOrRemove(Properties, \"{p.name}\", value);")
            out.append("    }")
            out.append("")
        out.append("}")
        out.append("")
    with open(os.path.join(OUT_DIR, "StyleOptions.g.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    # ---------- expression operators ----------
    with open(EXPR_HANDWRITTEN, encoding="utf-8") as f:
        handwritten = set(re.findall(r"public static Expression (\w+)\(", f.read()))
    ops = dict(ml["expression_name"]["values"])
    ops.update(mb["expression_name"]["values"])
    out = [header, "namespace Mapbox.Net.Style;\n", "public static partial class Expr", "{"]
    for op in sorted(ops):
        meta = ops[op] or {}
        name = OPERATOR_NAMES.get(op) or pascal(op)
        if name in handwritten:
            continue
        in_mb = op in mb["expression_name"]["values"]
        in_ml = op in ml["expression_name"]["values"]
        support = "Supported by Mapbox GL JS and MapLibre GL JS." if in_mb and in_ml else (
            "<b>Mapbox GL JS only.</b>" if in_mb else "<b>MapLibre GL JS only.</b>")
        group = meta.get("group", "")
        out += doc_lines(f"<c>{xml_doc(op)}</c> expression{(' (' + xml_doc(group) + ')') if group else ''}: {xml_doc(meta.get('doc', ''))}", [support])
        out.append(f"    public static Expression {name}(params object?[] args) => Expression.Create(\"{op}\", args);")
        out.append("")
    out.append("}")
    with open(os.path.join(OUT_DIR, "Expr.g.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    total_props = sum(len(p) + len(l) for (p, l, *_r) in layers.values())
    print(f"Generated {len(layers)} layer types, {total_props} layer properties, {len(enums.enums)} enums, "
          f"{len(roots)} option classes, {len(ops)} expression operators -> {OUT_DIR}")


if __name__ == "__main__":
    sys.exit(main())
